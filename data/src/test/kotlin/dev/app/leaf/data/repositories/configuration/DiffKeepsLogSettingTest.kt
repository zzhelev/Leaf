/** Whether the log stays above an open diff, through a real settings file (fork-only). */
class DiffKeepsLogSettingTest {
    @TempDir
    lateinit var dir: File

    private val scopes = mutableListOf<CoroutineScope>()
    private val settingsFile get() = File(dir, "user_prefs.json")

    @AfterEach
    fun cancelScopes() {
        scopes.forEach { it.cancel() }
    }

    /** One settings store on the file, as `DatastoreModule` builds it. Each call is a fresh start of the app. */
    private fun repository(): DataStoreAppSettingsRepository {
        runBlocking { scopes.forEach { it.coroutineContext.job.cancelAndJoin() } }
        scopes.clear()

        val scope = CoroutineScope(Dispatchers.IO + SupervisorJob()).also(scopes::add)
        val store: DataStore<Preferences> = PreferenceDataStoreFactory.create(
            storage = OkioStorage(
                FileSystem.SYSTEM,
                JsonPreferencesSerializer,
                producePath = { settingsFile.toOkioPath() },
            ),
            scope = scope,
        )

        return DataStoreAppSettingsRepository(
            UserSettingsDataStore(store),
            ThemeMapper(),
            LinesHeightMapper(),
            AvatarProviderMapper(),
            TextDiffViewTypeMapper(),
        )
    }

    @Test
    fun `without a choice the log stays, the new way`(): Unit = runBlocking {
        assertNull(repository().diffKeepsLog.first())
        assertEquals(true, AppSettingsService(repository()).diffKeepsLog.first())
    }

    @Test
    fun `turned off, the diff keeps the whole centre after a restart, under a key of its own`(): Unit = runBlocking {
        repository().setConfiguration(AppConfig.DiffKeepsLog(false))

        assertTrue(settingsFile.readText().contains("diff_keeps_log"), settingsFile.readText())
        assertEquals(false, AppSettingsService(repository()).diffKeepsLog.first())
        // The wrapping of the diff's lines is another setting
        assertEquals(true, AppSettingsService(repository()).diffWrapLines.first())

        repository().setConfiguration(AppConfig.DiffKeepsLog(true))

        assertEquals(true, AppSettingsService(repository()).diffKeepsLog.first())
    }
}
